    /// Gate case 359.7: validate-then-atomic-publish. A failed validation
    /// keeps the previous good generation byte-identical; a successful
    /// publish swaps the whole file (no missing/truncated window, no temp
    /// leftovers).
    #[test]
    fn publish_refuses_invalid_content_and_keeps_last_good_generation() {
        let (temp, _guards) = sandbox("publish-guard");
        let path = loader_path();
        let good = render_document(&sample_sections(), &BTreeSet::new());
        assert!(publish(&good).unwrap());
        let first_bytes = fs::read(&path).unwrap();
        assert_eq!(first_bytes, good.as_bytes());

        // An invalid generation is refused; the good one survives byte
        // for byte.
        assert!(publish("# not a loader\n").is_err());
        assert_eq!(fs::read(&path).unwrap(), first_bytes);

        // A changed generation publishes, and the swap leaves no temp
        // siblings behind.
        let updated = render_document(
            &[
                sample_sections()[0].clone(),
                LoaderSection {
                    id: "bash-it".to_string(),
                    body: "export BASH_IT='${HOME}/.niubash/sources/bash-it'\n".to_string(),
                },
            ],
            &BTreeSet::new(),
        );
        assert!(publish(&updated).unwrap());
        assert_eq!(fs::read(&path).unwrap(), updated.as_bytes());
        let leftovers: Vec<_> = fs::read_dir(temp.join("generated"))
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .filter(|name| name.contains(".tmp-"))
            .collect();
        assert!(leftovers.is_empty(), "temp siblings leaked: {leftovers:?}");

        // Republishing the same bytes is a no-op (idempotent).
        assert!(
            !publish(&updated).unwrap(),
            "byte-identical republish must not rewrite"
        );
    }

    #[test]
    fn startup_decision_matrix() {
        let (_temp, _guards) = sandbox("decision");
        let rc_clean = "export EDITOR=vim\n";
        let rc_legacy = "# >>> niu source oh-my-bash >>>\nOSH_THEME='robbyrussell'\n# <<< niu source oh-my-bash <<<\n";
        let loader = render_document(&sample_sections(), &BTreeSet::new());

        // No loader: missing, whatever the rc says.
        assert_eq!(
            startup_decision(Some(rc_clean), None),
            StartupDecision::Missing
        );
        // Loader + clean rc → load.
        assert_eq!(
            startup_decision(Some(rc_clean), Some(&loader)),
            StartupDecision::Load
        );
        // Loader + no rc → load (nothing to double with).
        assert_eq!(startup_decision(None, Some(&loader)), StartupDecision::Load);
        // Loader + legacy block in the rc → skip (double-execution guard).
        assert_eq!(
            startup_decision(Some(rc_legacy), Some(&loader)),
            StartupDecision::SupersededBlockPresent
        );
        // The rollback switch wins over everything.
        let previous = std::env::var_os("NIU_PLUGIN_LOADER");
        std::env::set_var("NIU_PLUGIN_LOADER", "off");
        assert_eq!(
            startup_decision(Some(rc_clean), Some(&loader)),
            StartupDecision::OptedOut
        );
        match previous {
            Some(value) => std::env::set_var("NIU_PLUGIN_LOADER", value),
            None => std::env::remove_var("NIU_PLUGIN_LOADER"),
        }
    }

    /// The double-execution scan recognizes every marker shape the product
    /// ever wrote: exact, near (hand-edited decoration), either direction,
    /// any id — plus the exact markers the loader records as superseded.
    #[test]
    fn marker_scan_covers_exact_near_and_recorded_shapes() {
        let (temp, _guards) = sandbox("scan");
        let _ = &temp;
        let cases = [
            "# >>> niu source oh-my-bash >>>",
            "# <<< niu source oh-my-bash <<<",
            "# >>> niu source bash-it >>>",
            "  # >>> niu source some-wild-tree >>>",
            "# >> niu source hand-edited (older wording)",
            "#<<< niu source squeezed <<<",
        ];
        for line in cases {
            let rc = format!("before\n{line}\nafter\n");
            assert!(rc_carries_superseded_markers(&rc), "must flag: {line}");
        }
        // Ordinary user lines and non-marker comments never trip it.
        assert!(!rc_carries_superseded_markers(
            "# a comment\ngrep '>>>' file\nalias ll='ls -la'\n"
        ));
        // A recorded superseded marker with an arbitrary spelling is
        // honored.
        let marker = "# >>> niu source future-wording >>>";
        let mut superseded = BTreeSet::new();
        superseded.insert(marker.to_string());
        let doc = render_document(&sample_sections(), &superseded);
        let _ = fs::create_dir_all(loader_path().parent().unwrap());
        fs::write(loader_path(), &doc).unwrap();
        assert!(rc_carries_superseded_markers(&format!("x\n{marker}\n")));
        assert!(!rc_carries_superseded_markers("clean\n"));
    }

